HEADER_TEMPLATE = (HEADER_TEMPLATE + b"\xFF" * 0x400)[:0x400]
assert len(HEADER_TEMPLATE) == 0x400

# Larghezza nei bit 0-2 (4 = 32 bit), velocita' nei bit 3-4 (0 = 10 clock,
# 8 = 8, 16 = 6, 24 = 5). Resta la combinazione conservativa 32 bit / 10 clock,
# quella con cui i cart commerciali sono stati testati.
#
# Provato in S29: portarla a 0x1C (5 clock) NON cambia un solo tick dei tempi di
# caricamento su BigPEmu, che quindi la ignora. Il che vuol dire due cose: che
# la lentezza misurata li' non viene dalle attese della cartuccia, e che su
# hardware vero il confronto e' ancora da fare.
CART_CONFIG = 0x04


def write_boot_header(cart, entry_point):
    """Scrive i primi $410 byte dell'immagine (cart = bytearray, in place).

    Lo stub $F6 non usa il checksum a $410-$41B: lasciarlo a $FF evita di
    sommare 1,5 milioni di word a ogni avvio.
    """
    cart[0:0x400] = HEADER_TEMPLATE
    for i in range(4):
        cart[0x400 + i] = CART_CONFIG
    struct.pack_into(">I", cart, 0x404, entry_point)
    struct.pack_into(">I", cart, 0x408, 0)
