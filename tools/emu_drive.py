#!/usr/bin/env python3
"""JagLBA S51 - the BigPEmu driving script, generated.

Writes a BigPEmu script module that PRESSES BUTTONS by writing the HAL cell
EMU_PAD (tools/memory_map.py, HAL_FIELDS) and PRINTS watched variables on the
emulator's HUD. It drives the game from inside the emulator: nothing is ever
sent to the desktop's keyboard, so it cannot type into the user's windows.

    emu_drive.py --press "A@700+6,A@1300+6,UP@2000+120" \
                 --watch front_done,bg_built,TimerRef \
                 --out D:\\...\\Scripts\\jaglba_drive.c

  --press  BUTTON@FRAME+LEN, comma separated. BUTTON is a PAD_* name (UP DOWN
           LEFT RIGHT A B C OPTION PAUSE) or K0..K9, STAR, HASH for the
           keypad. FRAME counts emulated frames from power-on.
  --watch  symbols of engine_c/engine_blob.sym (or obj_fork, see --sym),
           read as 32-bit longs every 30 frames. Addresses are baked in at
           generation time, so regenerate after every build.

Why generated: the addresses move with every build of the C blob, and a
probe that reads a stale address reads a plausible-looking wrong value
([[reference_bigpemu_script_probe]]: always a calibration line). The first
printed line is the calibration: the ROM's first instruction at $802000,
which must read 46FC2700 (move.w #$2700,sr).
"""
import argparse, os, re, sys

REPO = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import memory_map as mm

PAD = {'UP': 0x0001, 'DOWN': 0x0002, 'LEFT': 0x0004, 'RIGHT': 0x0008,
       'A': 0x0010, 'B': 0x0020, 'C': 0x0040, 'OPTION': 0x0080,
       'PAUSE': 0x0100}
for k in range(10):
    PAD['K%d' % k] = (1 << k) << 16
PAD['STAR'] = (1 << 10) << 16
PAD['HASH'] = (1 << 11) << 16


def hal_addr(name):
    base = mm.region('HAL_VARS')[0]
    for n, off, size, _ in mm.HAL_FIELDS:
        if n == name:
            return mm.DRAM_BASE + base + off if hasattr(mm, 'DRAM_BASE') else base + off
    raise SystemExit('emu_drive: no HAL field %s' % name)


def load_sym(path):
    syms = {}
    with open(path, encoding='utf-8', errors='replace') as f:
        for line in f:
            p = line.split()
            if len(p) == 3:
                syms[p[2]] = int(p[0], 16)
    return syms


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--press', default='')
    ap.add_argument('--watch', default='')
    ap.add_argument('--sym', default=os.path.join(REPO, 'engine_c',
                                                  'engine_blob.sym'))
    ap.add_argument('--out', required=True)
    a = ap.parse_args()

    presses = []
    for item in filter(None, [s.strip() for s in a.press.split(',')]):
        m = re.match(r'^([A-Z0-9]+)@(\d+)\+(\d+)$', item.upper())
        if not m or m.group(1) not in PAD:
            raise SystemExit('emu_drive: bad press %r' % item)
        presses.append((int(m.group(2)), int(m.group(3)), PAD[m.group(1)]))

    syms = load_sym(a.sym)
    watch = []
    for name in filter(None, [s.strip() for s in a.watch.split(',')]):
        # "sym", or "sym+OFF" with OFF decimal or 0x hex: a field inside a
        # struct or an array element (ListObjet+134*3+0x1A).
        m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*)((?:[+][0-9xXa-fA-F*]+)*)$', name)
        if not m or m.group(1) not in syms:
            raise SystemExit('emu_drive: %s not in %s' % (name, a.sym))
        off = 0
        for term in filter(None, m.group(2).split('+')):
            v = 1
            for f in term.split('*'):
                v *= int(f, 0)
            off += v
        watch.append((name, syms[m.group(1)] + off))

    emu_pad = hal_addr('EMU_PAD')

    out = []
    w = out.append
    w('//__BIGPEMU_SCRIPT_MODULE__')
    w('//__BIGPEMU_META_DESC__\t\t"JagLBA: guida dal pad dello script + sonde (tools/emu_drive.py)"')
    w('//__BIGPEMU_META_AUTHOR__\t"JagLBA S51"')
    w('// GENERATED by tools/emu_drive.py - do not edit, regenerate.')
    w('#include "bigpcrt.h"')
    w('#include "jagregs.h"')
    w('#define EMU_PAD 0x%08X' % emu_pad)
    w('static int sEv = -1;')
    w('static uint32_t sFrame = 0;')
    w('static const uint32_t kPress[][3] = {')
    for start, length, bits in presses:
        w('    { %d, %d, 0x%08X },' % (start, length, bits))
    w('    { 0xFFFFFFFF, 0, 0 } };')
    w('static uint32_t on_emu_frame(const int32_t eventHandle, void *pEventData)')
    w('{')
    w('    uint32_t bits = 0, i;')
    w('    sFrame++;')
    w('    for (i = 0; kPress[i][0] != 0xFFFFFFFF; i++)')
    w('        if (sFrame >= kPress[i][0] && sFrame < kPress[i][0] + kPress[i][1])')
    w('            bits |= kPress[i][2];')
    w('    if (sFrame > 60)')
    w('        bigpemu_jag_write32(EMU_PAD, bits);')
    w('    if (sFrame > 60 && (sFrame % 30) == 0) {')
    w('        printf_notify("f=%u cal=%08X pad=%08X", (unsigned)sFrame,'
      ' (unsigned)bigpemu_jag_read32(0x802000), (unsigned)bits);')
    for i in range(0, len(watch), 3):
        grp = watch[i:i + 3]
        fmt = '  '.join('%s=%%08X' % n.replace('ListObjet', 'LO') for n, _ in grp)
        args = ', '.join('(unsigned)bigpemu_jag_read32(0x%08X)' % ad
                         for _, ad in grp)
        w('        printf_notify("%s", %s);' % (fmt, args))
    w('    }')
    w('    return 0;')
    w('}')
    w('void bigp_init()')
    w('{')
    w('    void *pMod = bigpemu_get_module_handle();')
    w('    sEv = bigpemu_register_event_emu_thread_frame(pMod, on_emu_frame);')
    w('    printf_notify("JagLBA: guida S51 attiva");')
    w('}')
    w('void bigp_shutdown()')
    w('{')
    w('    void *pMod = bigpemu_get_module_handle();')
    w('    bigpemu_unregister_event(pMod, sEv);')
    w('    sEv = -1;')
    w('}')
    with open(a.out, 'w', encoding='ascii', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('emu_drive: %d presses, %d watches, EMU_PAD at $%06X -> %s'
          % (len(presses), len(watch), emu_pad, a.out))


if __name__ == '__main__':
    main()
