#!/usr/bin/env python3
"""S15 B1: pack body sphere section to Jaguar cart blob.

Output format (big-endian, Jaguar 68k native):
  WORD nb_spheres
  Per sphere (8 byte):
    BYTE coul1               ; 8bpp CLUT index for flat fill (V0)
    BYTE radius_screen       ; pre-computed (rayon * 34) >> 9, clamp 1..63
    WORD vert_off            ; = v_idx * 4 (VERT_LIST stride: WORD sx + WORD sy)
    LONG reserved            ; future: coul2, raw world rayon, mat byte, ...

Body 0 = 2 + 5*8 = 42 bytes. Per body the tool emits both .bin and .inc.
"""

import os, sys, struct, argparse

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hqr_decompress import parse_offsets, extract_entry
from body_sphere_dump import parse_body_full, iso_screen_radius


def pack_body_spheres(payload, body_idx):
    info = parse_body_full(payload)
    spheres = info['spheres']
    verts = info['verts']

    # S15-beta: iso painter back-to-front sort. Key = sum(X+Y+Z) of sphere
    # center vertex (LBA1 iso depth proxy, same as S13 SortPolysByZ).
    # Ascending key = back-to-front draw order (drawn last = on top).
    # Body T-pose static -> pack-time sort sufficient (no runtime cost).
    def key_of(sp):
        v = verts[sp['v_idx']]
        return v[0] + v[1] + v[2]
    spheres = sorted(spheres, key=key_of)

    out = bytearray()
    out += struct.pack('>H', len(spheres))  # BE WORD nb_spheres

    for sp in spheres:
        v_idx = sp['v_idx']
        if v_idx >= len(verts):
            print(f"  WARN: body {body_idx} sphere {sp} v_idx {v_idx} out of range")
            continue
        rs = iso_screen_radius(sp['rayon'])
        rs = max(1, min(63, rs))  # clamp 1..63
        coul1 = sp['coul1']
        vert_off = v_idx * 4  # VERT_LIST stride 4 byte (sx+sy WORD)

        # 8-byte BE struct
        out += struct.pack('>BBHL', coul1, rs, vert_off, 0)

    return bytes(out), spheres


def emit_inc(blob, body_idx):
    """Emit RMAC .dc.b directives as alternative to .incbin."""
    lines = [f"; Body {body_idx} sphere pack -- auto-generated by body_sphere_pack.py"]
    lines.append(f"Body{body_idx:03d}Spheres:")
    for off in range(0, len(blob), 8):
        chunk = blob[off:off+8]
        hexs = ', '.join(f'${b:02x}' for b in chunk)
        lines.append(f"\t.dc.b\t{hexs}")
    return '\n'.join(lines) + '\n'


def emit_disk_lut_inc(out_path):
    """Emit DiskHwLUT: 16 radii x 16 byte = 256 byte half-width table.
    Index: LUT[rs*16 + |dy|] = floor(sqrt(rs*rs - dy*dy)) for |dy| <= rs, else 0.
    Used by DrawBodySphere 68k routine for per-row scanline fill."""
    lines = [
        "; DiskHwLUT -- auto-generated by body_sphere_pack.py",
        "; 16 radii (rs=0..15) x 16-byte stride. byte[rs*16+|dy|] = half-width.",
        "; Half-width hw means: row at cy+dy spans cx-hw..cx+hw inclusive.",
        "; Empty rows (|dy| > rs): hw=0 (single pixel) -- caller must clip |dy|>rs.",
        "DiskHwLUT:",
    ]
    for rs in range(16):
        rs2 = rs * rs
        row = []
        for dy in range(16):
            if dy > rs:
                row.append(0)
                continue
            target = rs2 - dy * dy
            hw = 0
            while (hw + 1) ** 2 <= target:
                hw += 1
            row.append(hw)
        comment = f"; rs={rs:>2}, hw[|dy|=0..15]"
        bytes_str = ', '.join(f'${b:02x}' for b in row)
        lines.append(f"\t.dc.b\t{bytes_str}\t{comment}")
    with open(out_path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--body-hqr', default=r'I:\GOG\Little Big Adventure\Common\BODY.HQR')
    ap.add_argument('--body-idx', type=int, default=0)
    ap.add_argument('--out-dir', default='extracted/BODY_PACK')
    args = ap.parse_args()

    with open(args.body_hqr, 'rb') as f:
        data = f.read()
    offsets = parse_offsets(data)
    payload = extract_entry(data, args.body_idx, offsets)
    if payload is None:
        print(f"ERROR: body {args.body_idx} not extractable")
        return 1

    blob, spheres = pack_body_spheres(payload, args.body_idx)

    os.makedirs(args.out_dir, exist_ok=True)
    bin_path = os.path.join(args.out_dir, f'body_{args.body_idx:03d}_sph.bin')
    inc_path = os.path.join(args.out_dir, f'body_{args.body_idx:03d}_sph.inc')
    lut_path = os.path.join(args.out_dir, 'disk_hw_lut.inc')

    with open(bin_path, 'wb') as f:
        f.write(blob)
    with open(inc_path, 'w') as f:
        f.write(emit_inc(blob, args.body_idx))
    emit_disk_lut_inc(lut_path)
    print(f"  -> {lut_path}")

    print(f"=== Body {args.body_idx} sphere pack ===")
    print(f"  spheres: {len(spheres)}")
    print(f"  blob size: {len(blob)} bytes")
    print(f"  -> {bin_path}")
    print(f"  -> {inc_path}")
    print()
    print(f"  Per-sphere summary:")
    print(f"  {'idx':>3}  {'coul1':>5}  {'rs':>3}  {'v_idx':>5}  {'vert_off':>8}")
    for i, sp in enumerate(spheres):
        rs = max(1, min(63, iso_screen_radius(sp['rayon'])))
        print(f"  {i:>3}  {sp['coul1']:>5}  {rs:>3}  {sp['v_idx']:>5}  {sp['v_idx']*4:>8}")

    # Hex dump of blob
    print()
    print(f"  Blob hex dump:")
    for off in range(0, len(blob), 16):
        chunk = blob[off:off+16]
        hexs = ' '.join(f'{b:02x}' for b in chunk)
        print(f"  +{off:03x}: {hexs}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
