#!/usr/bin/env python3
"""S14 B1: pack baked per-corner intensity for one body into a side-blob.

Output: body_NNN_int.bin — fixed 4-byte slot per poly, indexed by poly_idx.
This is a SIDE BLOB to body_NNN.bin (preserved unchanged by body_pack.py),
so existing scene_viewer.s S13 paths keep working without format change.
S14 GpuRasterGouraud loads this blob in DRAM and indexes by poly_idx.

Slot layout (4 byte BE):
  Gouraud (mat 9-10):
    +0 u8 intensity_corner_0  (0..15 in low nibble; high nibble = 0)
    +1 u8 intensity_corner_1
    +2 u8 intensity_corner_2
    +3 u8 intensity_corner_3  (or 0xFF if nbp == 3)
  Flat (mat 7-8):
    +0 u8 intensity            (single value, 0..15)
    +1 u8 0xFF
    +2 u8 0xFF
    +3 u8 0xFF
  Pattern (mat 0-6):
    all 4 bytes = 0xFF (no lighting; renderer skips intensity branch)

Why 4-byte fixed slot (not variable, not 6=MAX_NBP):
  - Body 0 max nbp = 4, fits exactly.
  - 32-bit long alignment → trivial 68k indexing: addr = blob_base + poly_idx*4.
  - 224 polys * 4 = 896 byte total for body 0, negligible.
  - Bodies with nbp 5-6 (rare) would need extension; revisit when needed.

Ordering note:
  Poly order in this blob matches body_pack.py's order 1:1 (no tessellation
  for nbp <= 6). Verified against body_pack.fan_triangulate threshold = 6.
"""

import os as _os, sys as _sys
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
import lba_paths
import os, sys, struct, argparse, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from hqr_decompress import parse_offsets, extract_entry
from body_lighting import (
    parse_body, bake_body_intensity, DEFAULT_NORMAL_LIGHT,
)

SLOT_SIZE = 4
PAD = 0xFF


def pack_intensity(body):
    """Build the side-blob for a body. Body must have intensities populated
    via bake_body_intensity. For flat polys, replicate single intensity across
    nbp corners so DrawBodyFlat can blindly read bytes 0..nbp-1 per slot.
    Pattern polys: all bytes = 0 (graceful flat shading at coul1)."""
    out = bytearray()
    stats = {'gouraud': 0, 'flat': 0, 'pattern': 0,
             'intensity_hist': [0] * 16}
    for p in body['polys']:
        slot = bytearray([PAD, PAD, PAD, PAD])
        nbp = p['nbp']
        if p['mat'] >= 9:  # gouraud
            stats['gouraud'] += 1
            for k in range(min(nbp, 4)):
                v = p['intensities'][k] & 0x0F
                slot[k] = v
                stats['intensity_hist'][v] += 1
        elif p['mat'] >= 7:  # flat: replicate single intensity to nbp corners
            stats['flat'] += 1
            v = p['intensities'][0] & 0x0F
            for k in range(min(nbp, 4)):
                slot[k] = v
                stats['intensity_hist'][v] += 1
        else:  # pattern: write 0 to nbp corners (graceful flat at coul1)
            stats['pattern'] += 1
            for k in range(min(nbp, 4)):
                slot[k] = 0
                stats['intensity_hist'][0] += 1
        out += bytes(slot)
    return bytes(out), stats


def write_inc(blob, body_idx, out_path):
    """Generate .inc file with RMAC .dc.b directives for the blob.
    Format: 16 bytes per line for readability."""
    lines = [f"; Auto-generated by body_intensity_pack.py for body {body_idx}.",
             f"; {len(blob)} bytes = {len(blob)//4} polys * 4-byte slots.",
             f"; Slot layout: byte k = intensity 4-bit (0..15) for corner k.",
             f"; 0xFF = unused corner (nbp < 4 padding).",
             f""]
    for i in range(0, len(blob), 16):
        chunk = blob[i:i+16]
        hex_bytes = ','.join(f"${b:02X}" for b in chunk)
        lines.append(f"    .dc.b   {hex_bytes}")
    with open(out_path, 'w', encoding='ascii') as f:
        f.write('\n'.join(lines) + '\n')


def report(body_idx, blob, stats):
    print(f"=== Body {body_idx} intensity blob ===")
    n_poly = len(blob) // SLOT_SIZE
    print(f"  Slot count:          {n_poly}  (4 byte each)")
    print(f"  Total blob size:     {len(blob)} bytes")
    print(f"  Per-bucket counts:")
    print(f"    gouraud: {stats['gouraud']}")
    print(f"    flat:    {stats['flat']}")
    print(f"    pattern: {stats['pattern']}  (no lighting, all 0xFF slot)")
    n_total = sum(stats['intensity_hist'])
    if n_total:
        print(f"  Lit-corner intensity histogram (n={n_total}):")
        for s in range(16):
            c = stats['intensity_hist'][s]
            if c:
                print(f"    shade {s:>2}: {c:>4}  ({100*c/n_total:>4.1f}%)")


def verify_blob(blob, body):
    """Decode the blob and assert it matches expected per-poly bucket layout
    (post-replication for flat polys, pattern polys write 0 to nbp corners)."""
    n_poly = len(body['polys'])
    assert len(blob) == n_poly * SLOT_SIZE, \
        f"blob size {len(blob)} != {n_poly}*4"
    for i, p in enumerate(body['polys']):
        slot = blob[i*SLOT_SIZE:(i+1)*SLOT_SIZE]
        nbp = p['nbp']
        if p['mat'] >= 9:  # gouraud: per-corner
            for k in range(min(nbp, 4)):
                expected = p['intensities'][k] & 0x0F
                assert slot[k] == expected, \
                    f"poly {i} gouraud corner {k}: blob {slot[k]} != expected {expected}"
        elif p['mat'] >= 7:  # flat: replicated single intensity to nbp corners
            expected = p['intensities'][0] & 0x0F
            for k in range(min(nbp, 4)):
                assert slot[k] == expected, \
                    f"poly {i} flat corner {k}: blob {slot[k]} != replicated {expected}"
        else:  # pattern: 0 to nbp corners
            for k in range(min(nbp, 4)):
                assert slot[k] == 0, \
                    f"poly {i} pattern corner {k}: blob {slot[k]} != 0"
        # Padding bytes nbp..3 should remain 0xFF (unused).
        for k in range(nbp, 4):
            assert slot[k] == PAD, \
                f"poly {i} padding corner {k}: blob {slot[k]:02X} != FF"
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--body-hqr', default=lba_paths.common('BODY.HQR'))
    ap.add_argument('--body-idx', type=int, default=0)
    ap.add_argument('--out-dir', default=lba_paths.repo(r'extracted\BODY_PACK'))
    ap.add_argument('--lx', type=float, default=0.5774)
    ap.add_argument('--ly', type=float, default=0.5774)
    ap.add_argument('--lz', type=float, default=0.5774)
    ap.add_argument('--mode', choices=['cosine', 'lba_range'], default='cosine')
    args = ap.parse_args()

    light = (args.lx, args.ly, args.lz)
    mag = math.sqrt(sum(c*c for c in light))
    if abs(mag - 1.0) > 0.01:
        light = tuple(c / mag for c in light)

    with open(args.body_hqr, 'rb') as f:
        data = f.read()
    offs = parse_offsets(data)
    payload = extract_entry(data, args.body_idx, offs)
    if payload is None:
        sys.exit(f"BODY entry {args.body_idx} blank")

    body = parse_body(payload)
    bake_body_intensity(body, light, mode=args.mode)

    blob, stats = pack_intensity(body)
    report(args.body_idx, blob, stats)
    verify_blob(blob, body)
    print(f"  Roundtrip verify:    OK")

    os.makedirs(args.out_dir, exist_ok=True)
    out_path = os.path.join(args.out_dir, f'body_{args.body_idx:03d}_int.bin')
    with open(out_path, 'wb') as f:
        f.write(blob)
    print(f"  Written (binary):    {out_path}")

    inc_path = os.path.join(args.out_dir, f'body_{args.body_idx:03d}_int.inc')
    write_inc(blob, args.body_idx, inc_path)
    print(f"  Written (RMAC inc):  {inc_path}")


if __name__ == '__main__':
    main()
